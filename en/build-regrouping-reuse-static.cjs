'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const enDir = __dirname;
const templatePath = path.join(enDir, 'area-and-perimeter.html');
const adapterPath = path.join(enDir, 'banks', 'regrouping-reuse.js');
const manifestPath = path.join(enDir, 'regrouping-reuse-static-manifest.json');
const SITE = 'https://googoodan.com';
const VERSION = '20260914-regrouping-english';

function loadDefinitions() {
  const sandbox = {
    Worksheets: {types: []},
    KoMath: {profiles() { return []; }, generate() { return []; }}
  };
  sandbox.globalThis = sandbox;
  vm.runInNewContext(fs.readFileSync(adapterPath, 'utf8'), sandbox, {filename: adapterPath});
  return sandbox.RegroupingReuse.definitions;
}

function escapeText(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function escapeAttr(value) {
  return escapeText(value).replaceAll('"', '&quot;');
}

function operationName(def) {
  return def.op === '+' ? 'addition' : def.op === '−' ? 'subtraction' : 'multiplication';
}

function shortTitle(def) {
  const operation = def.op === '+' ? 'Addition' : def.op === '−' ? 'Subtraction' : 'Multiplication';
  const digits = def.digits === 2 ? '2-Digit' : '3-Digit';
  const count = def.target === 0 ? 'No Regrouping' : def.target + ' ' + (def.target === 1 ? 'Regrouping' : 'Regroupings');
  return (def.op === '×' ? digits + ' × 1-Digit: ' + count : digits + ' ' + operation + ': ' + count) + ' | Googoodan';
}

function metaDescription(def) {
  const count = def.target === 0 ? 'without regrouping' : 'with exactly ' + def.target + ' regrouping ' + (def.target === 1 ? 'step' : 'steps');
  const factors = def.op === '×'
    ? (def.digits === 2 ? 'two' : 'three') + '-digit by one-digit multiplication'
    : (def.digits === 2 ? 'two' : 'three') + '-digit ' + operationName(def);
  return 'Free printable Grade ' + def.grade + ' ' + factors + ' worksheets ' + count + '. Make new problems and print a matching answer key.';
}

function guideCopy(def, siblings) {
  const operation = operationName(def);
  const count = def.target === 0 ? 'no regrouping steps' : 'exactly ' + def.target + ' regrouping ' + (def.target === 1 ? 'step' : 'steps');
  const place = def.digits === 2 ? 'ones and tens places' : 'ones, tens, and hundreds places';
  const method = def.op === '+'
    ? 'Students add from right to left and record a new ten or hundred only when a place-value sum reaches 10. This focused set is filtered by the established source generator so each calculation has ' + count + '.'
    : def.op === '−'
      ? 'Students subtract from right to left and exchange one unit from the next place only when the top digit is too small. The established source generator guarantees ' + count + ' in every calculation.'
      : 'Students multiply the one-digit factor by each place from right to left, carrying to the next place only when needed. The established source generator guarantees ' + count + ' across the partial calculation.';
  const standardSentence = def.standard === '2.NBT.B.7'
    ? 'This page supports place-value strategies for adding and subtracting in the Grade 2 hundreds range.'
    : def.standard === '3.NBT.A.2'
      ? 'This page provides focused Grade 3 fluency practice with three-digit addition or subtraction.'
      : 'This page provides focused Grade 4 practice multiplying a whole number by a one-digit whole number.';
  const siblingLinks = siblings
    .filter(item => item.id !== def.id)
    .slice(0, 6)
    .map(item => '<li><a href="/en/' + escapeAttr(item.id) + '.html">' + escapeText(item.title) + '</a></li>')
    .join('');
  return '<section class="seo-resource" aria-labelledby="regrouping-guide">' +
    '<h2 id="regrouping-guide">Practice ' + escapeText(operation) + ' with exact regrouping</h2>' +
    '<p><strong>' + escapeText(def.title) + '</strong> gives Grade ' + def.grade + ' students a precise place-value practice set. Every calculation is generated by the same tested arithmetic bank used by the Korean worksheet collection, then presented with English directions and an American grade-level reference.</p>' +
    '<h3>What students practice</h3>' +
    '<p>' + escapeText(method) + ' Students work across the ' + escapeText(place) + ', show their steps, find missing values by using inverse operations, and decide whether a sample calculation is correct.</p>' +
    '<p>' + escapeText(standardSentence) + ' It is aligned as targeted practice for Common Core ' + escapeText(def.standard) + ' rather than a complete assessment of every part of that standard.</p>' +
    '<h3>How to use the worksheet</h3>' +
    '<p>Begin with the first two calculations and ask the student to mark each place where a value is regrouped. The next two questions hide a number, so the learner must use the relationship between operations. The final two questions ask the learner to check and correct another calculation. This sequence moves from performing a method to explaining and checking it.</p>' +
    '<p>Choose <strong>New problems</strong> for a fresh set with the same exact regrouping condition. Use <strong>Worksheet</strong> and <strong>Answer key</strong> to preview the matching pages. You can print either page or both, and the browser can save the same pages as a PDF. No sign-up is required.</p>' +
    '<h3>Teaching tip</h3>' +
    '<p>Ask the learner to say which place is being regrouped and why. A spoken explanation such as “I exchanged one hundred for ten tens” is more useful than memorizing a mark above a digit. If an answer is incorrect, compare it with the matching answer key, correct one place at a time, and then generate another short set.</p>' +
    '<h3>Related exact-regrouping worksheets</h3><ul>' + siblingLinks + '</ul>' +
    '<p><a href="/en/grade-' + def.grade + '.html">Browse all Grade ' + def.grade + ' math worksheets</a> · <a href="/en/us-arithmetic.html?grade=' + def.grade + '">Browse United States arithmetic practice</a></p>' +
    '</section>';
}

function pageJsonLd(def, canonical, description) {
  return JSON.stringify({
    '@context': 'https://schema.org',
    '@graph': [
      {'@type': 'WebSite', '@id': SITE + '/#website', name: 'Googoodan', alternateName: 'googoodan', url: SITE},
      {
        '@type': ['WebPage', 'LearningResource'],
        '@id': canonical + '#worksheet',
        url: canonical,
        name: def.title,
        description,
        inLanguage: 'en-US',
        educationalLevel: 'Grade ' + def.grade,
        learningResourceType: 'Printable worksheet generator',
        teaches: def.standard,
        isAccessibleForFree: true,
        isPartOf: {'@id': SITE + '/#website'}
      }
    ]
  }).replace(/</g, '\\u003c');
}

function replaceOne(text, pattern, replacement, label) {
  const flags = pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g';
  const matches = text.match(new RegExp(pattern.source, flags));
  if (!matches || matches.length !== 1) throw new Error(label + ': expected one match, found ' + (matches ? matches.length : 0));
  return text.replace(pattern, replacement);
}

function transform(template, def, definitions) {
  const canonical = SITE + '/en/' + def.id + '.html';
  const description = metaDescription(def);
  const alternates =
    '<link rel="alternate" hreflang="en" href="' + canonical + '">' +
    '<link rel="alternate" hreflang="ko" href="' + SITE + '/ko/">' +
    '<link rel="alternate" hreflang="ja" href="' + SITE + '/ja/">' +
    '<link rel="alternate" hreflang="fr" href="' + SITE + '/fr/">' +
    '<link rel="alternate" hreflang="de" href="' + SITE + '/de/">' +
    '<link rel="alternate" hreflang="x-default" href="' + SITE + '/">';
  let html = template;
  html = replaceOne(html, /<title>.*?<\/title>/i, '<title>' + escapeText(shortTitle(def)) + '</title>', 'title');
  html = replaceOne(html, /<meta name="description" content="[^"]*">/i, '<meta name="description" content="' + escapeAttr(description) + '">', 'description');
  html = html.includes('<meta name="robots"')
    ? replaceOne(html, /<meta name="robots" content="[^"]*">/i, '<meta name="robots" content="index,follow">', 'robots')
    : html.replace(/(<meta name="description" content="[^"]*">)/i, '$1<meta name="robots" content="index,follow">');
  html = replaceOne(html, /<link rel="canonical" href="[^"]*">/i, '<link rel="canonical" href="' + canonical + '">', 'canonical');
  html = html.replace(/<link rel="alternate" hreflang="[^"]+" href="[^"]*">/gi, '');
  html = html.replace(/(<meta property="og:title")/i, alternates + '$1');
  html = replaceOne(html, /<meta property="og:title" content="[^"]*">/i, '<meta property="og:title" content="' + escapeAttr(def.title) + '">', 'og:title');
  html = replaceOne(html, /<meta property="og:description" content="[^"]*">/i, '<meta property="og:description" content="' + escapeAttr(description) + '">', 'og:description');
  html = replaceOne(html, /<meta property="og:url" content="[^"]*">/i, '<meta property="og:url" content="' + canonical + '">', 'og:url');
  html = replaceOne(html, /<script id="website-identity" type="application\/ld\+json">.*?<\/script>/i, '<script id="website-identity" type="application/ld+json">' + pageJsonLd(def, canonical, description) + '</script>', 'JSON-LD');
  html = html.replace(/<script type="application\/ld\+json">.*?<\/script>/i, '');
  html = html.replace('<link rel="stylesheet" href="style.css', '<link rel="stylesheet" href="/en/style.css')
    .replace('<script defer src="types.js', '<script defer src="/en/types.js')
    .replace('<script defer src="curriculum.js', '<script defer src="/en/curriculum.js')
    .replace('<script defer src="app.js', '<script defer src="/en/app.js')
    .replace('<link rel="stylesheet" href="legal.css', '<link rel="stylesheet" href="/en/legal.css');
  html = html.replace(/<link rel="stylesheet" href="\/en\/banks\/coverage\.css[^"]*">/i, '<link rel="stylesheet" href="/en/banks/regrouping-reuse.css?v=' + VERSION + '">')
    .replace(/<script defer src="\/en\/banks\/coverage-controls\.js[^"]*"><\/script>/i, '')
    .replace(/<script defer src="\/en\/banks\/coverage\.js[^"]*"><\/script>/i,
      '<script defer src="/ko/art/catalog.js?v=20260910"></script>' +
      '<script defer src="/ko/art.js?v=20260910"></script>' +
      '<script defer src="/ko/banks/arithmetic-targets.js?v=20260910"></script>' +
      '<script defer src="/en/banks/regrouping-reuse.js?v=' + VERSION + '"></script>');
  html = replaceOne(html, /<body data-type="[^"]*" data-base="[^"]*">/i, '<body data-type="' + escapeAttr(def.id) + '" data-base="/en/">', 'body data');
  html = html.replace('<a class="logo" href="index.html">', '<a class="logo" href="/en/">');
  html = replaceOne(html, /<aside><h1>.*?<\/h1><p>.*?<\/p>/i, '<aside><h1>' + escapeText(def.title) + '</h1><p>' + escapeText(description) + '</p>', 'visible H1');
  html = replaceOne(html, /<h2 id="sheet-title">.*?<\/h2>/i, '<h2 id="sheet-title">' + escapeText(def.title) + '</h2>', 'sheet title');
  html = replaceOne(html, /<p class="instructions" id="instructions">.*?<\/p>/i,
    '<p class="instructions" id="instructions">' + escapeText(def.op === '×' ? 'Multiply using place value. Show each regrouping step.' : 'Calculate using place value. Show each regrouping step.') + '</p>', 'instructions');
  html = html.replace(/href="(about|contact|privacy|terms)\.html"/g, 'href="/en/$1.html"')
    .replace(/href="index\.html"/g, 'href="/en/"');
  html = replaceOne(html, /<section class="seo-resource"[\s\S]*?<\/section><\/body>/i,
    guideCopy(def, definitions.filter(item => item.grade === def.grade && item.op === def.op)) + '</body>', 'resource');
  return {html, canonical, description};
}

function build() {
  const definitions = loadDefinitions();
  if (definitions.length !== 17) throw new Error('Expected 17 definitions, found ' + definitions.length);
  const ids = new Set(definitions.map(def => def.id));
  const titles = new Set(definitions.map(def => def.title));
  if (ids.size !== definitions.length || titles.size !== definitions.length) throw new Error('Duplicate worksheet id or H1');
  const template = fs.readFileSync(templatePath, 'utf8');
  const pages = [];
  for (const def of definitions) {
    const built = transform(template, def, definitions);
    const file = path.join(enDir, def.id + '.html');
    fs.writeFileSync(file, built.html + '\n', 'utf8');
    pages.push({
      id: def.id,
      file: path.basename(file),
      canonical: built.canonical,
      title: shortTitle(def),
      h1: def.title,
      description: built.description,
      grade: def.grade,
      standard: def.standard,
      sourceUnit: def.sourceUnit,
      sourceProfile: def.sourceProfile,
      operation: operationName(def),
      digits: def.digits,
      exactRegroupings: def.target
    });
  }
  const manifest = {
    generatedAt: '2026-09-14',
    buildVersion: VERSION,
    count: pages.length,
    sources: ['ko/catalog.js', 'ko/engine.js', 'ko/banks/arithmetic-targets.js', 'en/banks/regrouping-reuse.js'],
    pages
  };
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  process.stdout.write('Built ' + pages.length + ' exact-regrouping pages.\n');
}

build();
